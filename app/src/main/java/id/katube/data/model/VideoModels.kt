package id.katube.data.model

import androidx.compose.runtime.Immutable

/**
 * Model domain untuk video YouTube.
 * UI HANYA boleh berinteraksi dengan kelas ini, BUKAN kelas NewPipeExtractor langsung.
 */
@Immutable
data class VideoItem(
    val id: String,
    val url: String,
    val title: String,
    val uploaderName: String,
    val uploaderAvatarUrl: String? = null,
    val uploaderUrl: String? = null,
    val durationSeconds: Long = 0,
    val viewCount: Long = 0,
    val uploadDateText: String? = null,
    val thumbnailUrl: String? = null,
    val isMix: Boolean = false,
    val playlistId: String? = null,
    val playbackPositionMs: Long = 0L,
    val playbackPercent: Float = 0f,
    val isLive: Boolean = false,
    val rawDurationText: String? = null,
) {
    /**
     * Persentase durasi tontonan (0.0f sampai 1.0f) untuk tanda pemutaran di thumbnail.
     */
    val watchProgress: Float
        get() {
            if (playbackPercent > 0f) return playbackPercent.coerceIn(0f, 1f)
            if (durationSeconds > 0 && playbackPositionMs > 0) {
                return (playbackPositionMs / (durationSeconds * 1000f)).coerceIn(0f, 1f)
            }
            return 0f
        }

    /**
     * URL thumbnail beresolusi tinggi (HQ/MaxRes) untuk tampilan jernih tanpa buram.
     */
    val highResThumbnailUrl: String?
        get() {
            val raw = thumbnailUrl ?: return if (id.isNotEmpty()) "https://i.ytimg.com/vi/$id/hqdefault.jpg" else null
            return if (raw.contains("/default.jpg")) {
                raw.replace("/default.jpg", "/hqdefault.jpg")
            } else if (raw.contains("/default.webp")) {
                raw.replace("/default.webp", "/hqdefault.webp")
            } else {
                raw
            }
        }

    /**
     * Format durasi detik menjadi string MM:SS atau HH:MM:SS, atau badge LIVE untuk siaran langsung.
     */
    val formattedDuration: String
        get() {
            if (isLive) return "LIVE"
            if (durationSeconds > 0) {
                val hours = durationSeconds / 3600
                val minutes = (durationSeconds % 3600) / 60
                val seconds = durationSeconds % 60
                return if (hours > 0) {
                    String.format("%d:%02d:%02d", hours, minutes, seconds)
                } else {
                    String.format("%d:%02d", minutes, seconds)
                }
            }
            if (!rawDurationText.isNullOrBlank()) {
                val clean = rawDurationText.trim().replace('.', ':')
                if (clean.equals("live", ignoreCase = true) || clean.equals("langsung", ignoreCase = true)) {
                    return "LIVE"
                }
                return clean
            }
            return ""
        }

    /**
     * Format jumlah views menjadi teks ringkas berbahasa Indonesia (contoh: 1,2 jt x).
     */
    val formattedViews: String
        get() {
            if (viewCount <= 0) return ""
            return when {
                viewCount >= 1_000_000_000 -> String.format("%.1f M x", viewCount / 1_000_000_000.0)
                viewCount >= 1_000_000 -> String.format("%.1f jt x", viewCount / 1_000_000.0)
                viewCount >= 1_000 -> String.format("%.1f rb x", viewCount / 1_000.0)
                else -> "$viewCount x"
            }
        }
}

/**
 * Model domain untuk Channel.
 */
@Immutable
data class ChannelItem(
    val id: String,
    val url: String,
    val name: String,
    val avatarUrl: String? = null,
    val bannerUrl: String? = null,
    val subscriberCount: Long = 0,
    val description: String? = null,
    val videos: List<VideoItem> = emptyList(),
    val playlists: List<PlaylistItem> = emptyList(),
) {
    val formattedSubscribers: String
        get() {
            if (subscriberCount <= 0) return ""
            return when {
                subscriberCount >= 1_000_000_000 -> String.format("%.1f M pelanggan", subscriberCount / 1_000_000_000.0)
                subscriberCount >= 1_000_000 -> String.format("%.1f jt pelanggan", subscriberCount / 1_000_000.0)
                subscriberCount >= 1_000 -> String.format("%.1f rb pelanggan", subscriberCount / 1_000.0)
                else -> "$subscriberCount pelanggan"
            }
        }
}

