/**
 * Paket stream yang siap diputar oleh ExoPlayer / Media3.
 * Menggabungkan stream video-only dan audio-only secara terpisah untuk kualitas maksimal.
 */
@Immutable
data class StreamBundle(
    val videoId: String,
    val title: String,
    val uploaderName: String,
    val uploaderAvatarUrl: String? = null,
    val uploaderUrl: String? = null,
    val thumbnailUrl: String? = null,
    val description: String? = null,
    val durationSeconds: Long = 0,
    val likeCount: Long = 0,
    val viewCount: Long = 0,
    val uploadDateText: String? = null,
    val selectedVideoUrl: String?,
    val selectedAudioUrl: String = "",
    val selectedHeight: Int = 0,
    val isLive: Boolean = false,
    val hlsUrl: String? = null,
    val availableQualities: List<VideoQuality> = emptyList(),
    val relatedVideos: List<VideoItem> = emptyList(),
    val fallbackAudioUrl: String? = null,
    val uploaderSubscriberCount: Long = 0,
    val uploaderSubscriberText: String? = null,
    val availableSubtitles: List<SubtitleItem> = emptyList(),
) {
    val formattedSubscribers: String
        get() {
            if (!uploaderSubscriberText.isNullOrBlank()) return uploaderSubscriberText
            if (uploaderSubscriberCount <= 0) return "Channel YouTube"
            return when {
                uploaderSubscriberCount >= 1_000_000_000 -> String.format("%.1f M subscriber", uploaderSubscriberCount / 1_000_000_000.0)
                uploaderSubscriberCount >= 1_000_000 -> String.format("%.1f jt subscriber", uploaderSubscriberCount / 1_000_000.0)
                uploaderSubscriberCount >= 1_000 -> String.format("%.1f rb subscriber", uploaderSubscriberCount / 1_000.0)
                else -> "$uploaderSubscriberCount subscriber"
            }
        }

    val formattedLikes: String
        get() {
            if (likeCount <= 0) return "Suka"
            return when {
                likeCount >= 1_000_000 -> String.format("%.1f jt", likeCount / 1_000_000.0)
                likeCount >= 1_000 -> String.format("%.1f rb", likeCount / 1_000.0)
                else -> "$likeCount"
            }
        }

    val formattedViews: String
        get() {
            if (viewCount <= 0) return ""
            return when {
                viewCount >= 1_000_000_000 -> String.format("%.1f M", viewCount / 1_000_000_000.0)
                viewCount >= 1_000_000 -> String.format("%.1f jt", viewCount / 1_000_000.0)
                viewCount >= 1_000 -> String.format("%.1f rb", viewCount / 1_000.0)
                else -> "$viewCount"
            }
        }
}

/**
 * Model domain untuk Komentar Video YouTube (Sesuai Referensi PDF Halaman 4).
 */
@Immutable
data class CommentItem(
    val id: String,
    val authorName: String,
    val authorAvatarUrl: String? = null,
    val text: String,
    val uploadDateText: String? = null,
    val likeCount: Int = 0,
    val isUserComment: Boolean = false,
) {
    val formattedLikes: String
        get() = if (likeCount > 0) "$likeCount" else ""

    val displayAuthorName: String
        get() {
            val clean = authorName.replace("@", "").trim()
            return if (clean.isNotEmpty()) clean else "Pengguna"
        }
}

