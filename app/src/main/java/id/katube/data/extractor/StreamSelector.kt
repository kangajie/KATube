package id.katube.data.extractor

import android.content.Context
import id.katube.core.util.CommentUtils
import id.katube.core.util.NetworkUtils
import id.katube.core.util.TimeAgoUtils
import id.katube.data.model.StreamBundle
import id.katube.data.model.VideoItem
import id.katube.data.model.VideoQuality
import org.schabi.newpipe.extractor.stream.DeliveryMethod
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.extractor.stream.StreamInfoItem
import org.schabi.newpipe.extractor.stream.StreamType

object StreamSelector {

    /**
     * Memilih kombinasi stream video dan audio terbaik untuk pemutaran.
     * YouTube memisahkan video dan audio kualitas tinggi (DASH/progressive).
     * @param maxHeight Resolusi yang diinginkan. Jika 0, berlaku mode Otomatis (Auto) sesuai kondisi jaringan.
     */
    fun select(info: StreamInfo, maxHeight: Int = 0, context: Context? = null): StreamBundle {
        val rawUrl = info.url.orEmpty()
        val videoId = when {
            rawUrl.contains("v=") -> rawUrl.substringAfter("v=").substringBefore("&")
            rawUrl.contains("youtu.be/") -> rawUrl.substringAfter("youtu.be/").substringBefore("?").substringBefore("&")
            rawUrl.isNotBlank() -> rawUrl.substringAfterLast("/").substringBefore("?")
            else -> info.id.orEmpty()
        }.ifEmpty { info.id.orEmpty() }

        // Petakan video terkait (rekomendasi)
        val relatedVideos = info.relatedStreams.orEmpty()
            .filterIsInstance<StreamInfoItem>()
            .map { item ->
                val safeUrl = item.url.orEmpty()
                val relId = when {
                    safeUrl.contains("v=") -> safeUrl.substringAfter("v=").substringBefore("&")
                    safeUrl.contains("youtu.be/") -> safeUrl.substringAfter("youtu.be/").substringBefore("?").substringBefore("&")
                    safeUrl.isNotBlank() -> safeUrl.substringAfterLast("/").substringBefore("?")
                    else -> ""
                }
                VideoItem(
                    id = relId,
                    url = safeUrl,
                    title = item.name.orEmpty(),
                    uploaderName = item.uploaderName.orEmpty(),
                    uploaderAvatarUrl = item.uploaderAvatars?.firstOrNull()?.url,
                    uploaderUrl = item.uploaderUrl,
                    durationSeconds = item.duration,
                    viewCount = item.viewCount,
                    uploadDateText = TimeAgoUtils.format(info.uploadDate, item.textualUploadDate),
                    thumbnailUrl = item.thumbnails?.lastOrNull()?.url
                        ?: item.thumbnails?.firstOrNull()?.url
                        ?: if (relId.isNotEmpty()) "https://i.ytimg.com/vi/$relId/hqdefault.jpg" else null,
                )
            }

        // Petakan subtitle / teks bahasa yang tersedia
        val availableSubtitles = try {
            info.subtitles.orEmpty().mapNotNull { sub ->
                val url = sub.content ?: sub.url
                if (!url.isNullOrBlank()) {
                    val langTag = sub.languageTag.orEmpty().ifEmpty { sub.locale?.language.orEmpty() }
                    val rawName = sub.displayLanguageName.orEmpty().ifEmpty { sub.locale?.displayName.orEmpty() }.ifEmpty { langTag }
                    val cleanName = when (langTag.lowercase()) {
                        "id", "in" -> "Bahasa Indonesia"
                        "en" -> "English"
                        "ja" -> "Japanese"
                        "ko" -> "Korean"
                        "ar" -> "Arabic"
                        "es" -> "Spanish"
                        "zh" -> "Chinese"
                        else -> rawName
                    }
                    id.katube.data.model.SubtitleItem(
                        url = url,
                        languageCode = langTag,
                        languageName = cleanName,
                        isAutoGenerated = sub.isAutoGenerated,
                        format = sub.extension.orEmpty().ifEmpty { "vtt" }
                    )
                } else null
            }.distinctBy { "${it.languageCode}_${it.isAutoGenerated}" }
        } catch (_: Exception) {
            emptyList()
        }

        val isLiveStream = info.streamType == StreamType.LIVE_STREAM && info.duration <= 0

        val rawLiveAvatar = info.uploaderAvatars?.lastOrNull()?.url
            ?: info.uploaderAvatars?.firstOrNull()?.url
            ?: info.subChannelAvatars?.lastOrNull()?.url
            ?: info.subChannelAvatars?.firstOrNull()?.url
        val cleanLiveAvatar = rawLiveAvatar?.let {
            val trimmed = it.trim()
            when {
                trimmed.startsWith("//") -> "https:$trimmed"
                trimmed.startsWith("http://") -> "https://" + trimmed.substringAfter("http://")
                else -> trimmed
            }
        }

        // 1. Penanganan Khusus Live Stream YouTube:
        // Live stream memuat video dan audio di playlist HLS m3u8 tanpa stream audio progresif terpisah.
        if (isLiveStream && !info.hlsUrl.isNullOrEmpty()) {
            val liveUploadDate = TimeAgoUtils.format(info.uploadDate, info.textualUploadDate).ifEmpty { "Sedang Live" }
            return StreamBundle(
                videoId = videoId,
                title = info.name.orEmpty(),
                uploaderName = info.uploaderName.orEmpty(),
                uploaderAvatarUrl = cleanLiveAvatar,
                uploaderUrl = info.uploaderUrl,
                thumbnailUrl = info.thumbnails?.lastOrNull()?.url
                    ?: info.thumbnails?.firstOrNull()?.url
                    ?: "https://i.ytimg.com/vi/$videoId/hqdefault.jpg",
                description = CommentUtils.cleanCommentText(info.description?.content),
                durationSeconds = 0L,
                likeCount = info.likeCount,
                viewCount = info.viewCount,
                uploadDateText = liveUploadDate,
                selectedVideoUrl = null,
                selectedAudioUrl = "",
                selectedHeight = 0,
                isLive = true,
                hlsUrl = info.hlsUrl,
                availableQualities = listOf(
                    VideoQuality(
                        height = 0,
                        label = "Live Auto",
                        url = info.hlsUrl.orEmpty(),
                        isMuxed = true
                    )
                ),
                relatedVideos = relatedVideos,
                fallbackAudioUrl = "",
                uploaderSubscriberCount = info.uploaderSubscriberCount,
                availableSubtitles = availableSubtitles,
            )
        }

        // Tentukan batas resolusi efektif (jika 0 / Auto, sesuaikan otomatis dengan kondisi koneksi)
        val targetHeight = if (maxHeight <= 0) {
            context?.let { NetworkUtils.getOptimalAutoResolution(it) } ?: 480
        } else {
            maxHeight
        }

        // 2. Pilah stream Muxed (Video + Audio tergabung dalam 1 file MP4) dan Video-Only (DASH)
        val muxedStreams = info.videoStreams.orEmpty().filter { it.height > 0 && !it.content.isNullOrEmpty() }
        val videoOnlyStreams = info.videoOnlyStreams.orEmpty().filter { it.height > 0 && !it.content.isNullOrEmpty() }

        // Fungsi pembobotan codec akselerasi hardware:
        // Prioritaskan H.264/AVC (MPEG_4 / avc1) karena didukung hardware decoder chip di 100% perangkat Android.
        // Hindari AV1 (av01) sebagai pilihan utama karena ponsel tanpa decoder hardware AV1 akan drop frames & lag parah!
        fun getCodecHardwareScore(stream: org.schabi.newpipe.extractor.stream.VideoStream): Int {
            val codec = stream.codec.orEmpty().lowercase()
            val format = stream.format
            return when {
                format == org.schabi.newpipe.extractor.MediaFormat.MPEG_4 || codec.startsWith("avc") -> 300
                codec.startsWith("vp9") || codec.startsWith("vp09") -> 200
                codec.startsWith("av01") || codec.startsWith("av1") -> 50
                else -> 100
            }
        }

        // 3. Pilih stream audio (digunakan untuk video bertipe Video-Only DASH seperti 1080p, atau fallback audio)
        val progressiveAudio = info.audioStreams.orEmpty().filter { it.deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP }.ifEmpty { info.audioStreams.orEmpty() }
        val aacAudioStreams = progressiveAudio.filter {
            it.format == org.schabi.newpipe.extractor.MediaFormat.M4A ||
            it.codec?.contains("mp4a", ignoreCase = true) == true
        }
        val candidateAudioStreams = aacAudioStreams.ifEmpty { progressiveAudio }

        val audio = if (candidateAudioStreams.isNotEmpty()) {
            if (targetHeight <= 240) {
                candidateAudioStreams.minByOrNull { it.averageBitrate } ?: candidateAudioStreams.firstOrNull()
            } else if (targetHeight <= 360) {
                candidateAudioStreams.sortedBy { it.averageBitrate }.getOrNull(candidateAudioStreams.size / 2) ?: candidateAudioStreams.firstOrNull()
            } else {
                candidateAudioStreams.maxByOrNull { it.averageBitrate } ?: candidateAudioStreams.firstOrNull()
            } ?: progressiveAudio.firstOrNull()
        } else {
            null
        }

        // 4. Daftar kualitas video yang tersedia untuk menu pilihan pengguna (urutkan codec terbaik lebih dulu sebelum distinct)
        val allVideoStreams = (muxedStreams + videoOnlyStreams)
        val normalQualities = allVideoStreams
            .sortedWith(
                compareByDescending<org.schabi.newpipe.extractor.stream.VideoStream> { it.height }
                    .thenByDescending { getCodecHardwareScore(it) }
                    .thenBy { it.fps }
            )
            .distinctBy { it.height }
            .map { stream ->
                VideoQuality(
                    height = stream.height,
                    label = "${stream.height}p" + if (stream.fps > 30) " ${stream.fps}fps" else "",
                    url = stream.content.orEmpty(),
                    isMuxed = muxedStreams.contains(stream)
                )
            }

        // Sisipkan opsi Otomatis di posisi teratas seperti YouTube
        val availableQualities = listOf(
            VideoQuality(
                height = 0,
                label = "Otomatis",
                url = "",
                isMuxed = false
            )
        ) + normalQualities

        // 5. Pilih stream video optimal sesuai targetHeight yang diminta user:
        // Jika user secara spesifik memilih kualitas tertentu (maxHeight > 0), prioritaskan resolusi persis yang dipilih!
        val exactMuxed = if (maxHeight > 0) muxedStreams.firstOrNull { it.height == targetHeight } else null
        val exactVideoOnly = if (maxHeight > 0) {
            videoOnlyStreams
                .filter { it.height == targetHeight }
                .sortedWith(
                    compareByDescending<org.schabi.newpipe.extractor.stream.VideoStream> { getCodecHardwareScore(it) }
                        .thenBy { it.fps }
                ).firstOrNull()
        } else null

        val candidateMuxed = muxedStreams
            .filter { it.height <= targetHeight }
            .maxByOrNull { it.height }

        val candidateVideoOnly = videoOnlyStreams
            .filter { it.height <= targetHeight }
            .sortedWith(
                compareByDescending<org.schabi.newpipe.extractor.stream.VideoStream> { it.height }
                    .thenByDescending { getCodecHardwareScore(it) }
                    .thenBy { it.fps }
            )
            .firstOrNull()

        val selectedVideo = if (exactMuxed != null) {
            exactMuxed
        } else if (exactVideoOnly != null) {
            exactVideoOnly
        } else if (candidateMuxed != null && candidateMuxed.height >= targetHeight) {
            candidateMuxed
        } else if (candidateVideoOnly != null) {
            if (candidateMuxed != null && candidateMuxed.height >= candidateVideoOnly.height) {
                candidateMuxed
            } else {
                candidateVideoOnly
            }
        } else if (candidateMuxed != null) {
            candidateMuxed
        } else {
            videoOnlyStreams.sortedWith(
                compareBy<org.schabi.newpipe.extractor.stream.VideoStream> { it.height }
                    .thenByDescending { getCodecHardwareScore(it) }
            ).firstOrNull() ?: muxedStreams.minByOrNull { it.height }
        }

        val actualIsUsingMuxed = (selectedVideo != null && muxedStreams.contains(selectedVideo))
        val audioUrl = if (actualIsUsingMuxed) "" else (audio?.content.orEmpty().ifEmpty { candidateMuxed?.content.orEmpty() })

        val rawAvatar = info.uploaderAvatars?.lastOrNull()?.url
            ?: info.uploaderAvatars?.firstOrNull()?.url
            ?: info.subChannelAvatars?.lastOrNull()?.url
            ?: info.subChannelAvatars?.firstOrNull()?.url
        val cleanAvatar = rawAvatar?.let {
            val trimmed = it.trim()
            when {
                trimmed.startsWith("//") -> "https:$trimmed"
                trimmed.startsWith("http://") -> "https://" + trimmed.substringAfter("http://")
                else -> trimmed
            }
        }

        return StreamBundle(
            videoId = videoId,
            title = info.name.orEmpty(),
            uploaderName = info.uploaderName.orEmpty(),
            uploaderAvatarUrl = cleanAvatar,
            uploaderUrl = info.uploaderUrl,
            thumbnailUrl = info.thumbnails?.lastOrNull()?.url
                ?: info.thumbnails?.firstOrNull()?.url
                ?: "https://i.ytimg.com/vi/$videoId/hqdefault.jpg",
            description = CommentUtils.cleanCommentText(info.description?.content),
            durationSeconds = info.duration,
            likeCount = info.likeCount,
            viewCount = info.viewCount,
            uploadDateText = TimeAgoUtils.format(info.uploadDate, info.textualUploadDate).ifEmpty { "Baru saja" },
            selectedVideoUrl = selectedVideo?.content,
            selectedAudioUrl = audioUrl,
            selectedHeight = selectedVideo?.height ?: 0,
            isLive = false,
            hlsUrl = info.hlsUrl,
            availableQualities = availableQualities,
            relatedVideos = relatedVideos,
            fallbackAudioUrl = audio?.content.orEmpty().ifEmpty { audioUrl },
            uploaderSubscriberCount = info.uploaderSubscriberCount,
            availableSubtitles = availableSubtitles,
        )
    }
}
